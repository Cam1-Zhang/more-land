export function conversationContext(s:ValleyState,id:string){
 const plan=residentPlan(s,id,chapterIndex(s)),tags=['any'];
 // A companion is with the player; do not claim they are doing their remote schedule.
 if(id===s.companion&&plan.place!==s.place)tags.push('companion');
 else {
  const activity=plan.activity;
  if(/面包|补给/.test(activity))tags.push('bread');
  if(/田地|田垄|种子|菜苗|农具|苹果树/.test(activity))tags.push('farm');
  if(/花|晾好/.test(activity))tags.push('flowers');
  if(/档案|记录|书|数据|旧物/.test(activity))tags.push('records');
  if(/工具|修缮|屋顶|器具/.test(activity))tags.push('repair');
  if(/河|水位|水流|船屋/.test(activity))tags.push('river');
  if(/散步|晒太阳/.test(activity))tags.push('walk');
  if(/草药|树枝|林间/.test(activity))tags.push('forest');
  if(id!=='43'&&/晚饭|吃饭|餐桌|点心|吧台|聚会/.test(activity))tags.push('meal');
  if(/天气|观测|云|风向/.test(activity))tags.push(s.minute>=1080?'observe-night':'observe');
  if(/采购|生活用品/.test(activity))tags.push('market');
 }
 if(s.place===HOME_OF[id])tags.push('home',s.minute>=1080?'home-night':'home-day');
 if(weather(s)==='雨')tags.push('rain');
 return {tags,activity:id===s.companion&&plan.place!==s.place?'与你同行':plan.activity,key:`${s.place}:${s.minute<720?'morning':s.minute<1080?'afternoon':'evening'}:${tags.join(',')}:story-${s.flags.length}-${s.flags.at(-1)??''}:bond-${(s.friendship[id]??0)>=30?'friend':'new'}`};
}

export function topicsFor(s:ValleyState,id:string){
 const {tags}=conversationContext(s,id);
 return ALL_DAILY_TOPICS.filter(t=>(!t.people||t.people.includes(id))&&(!t.requires||t.requires.every(f=>s.flags.includes(f)))&&!t.until?.some(f=>s.flags.includes(f))&&(s.friendship[id]??0)>=(t.minBond??0)&&(!t.tags||t.tags.some(tag=>tags.includes(tag))));
}
export const ALL_DAILY_TOPICS=[...SHARED_TOPICS,...PERSONAL_TOPICS,...STORY_TOPICS];
const TOPICS_BY_ID=new Map(ALL_DAILY_TOPICS.map(t=>[t.id,t]));
export function topicById(id:string){return TOPICS_BY_ID.get(id);}
