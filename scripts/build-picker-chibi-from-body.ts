/**
 * 从全身立绘生成选人/图鉴用 SD 像素风小人（缩略 + nearest 像素化，透明底无草皮）。
 * 输出：`assets/characters/chibi/named/{Name}.png` 与 `assets/characters/chibi/{id}.png`
 *
 * Usage: npm run build:picker-chibi
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

import sharp from 'sharp';

import { CHARACTERS } from '../src/data/mockData';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const BODY_NAMED = path.join(ROOT, 'assets', 'characters', 'body', 'named');
const BODY_NUM = path.join(ROOT, 'assets', 'characters', 'body');
/** `npm run gen:picker-chibi` 产出；若存在则优先于全身立绘做卡片缩放 */
const GEN_SRC = path.join(ROOT, 'assets', 'characters', 'chibi', 'generated-src');
const OUT_NAMED = path.join(ROOT, 'assets', 'characters', 'chibi', 'named');
const OUT_NUM = path.join(ROOT, 'assets', 'characters', 'chibi');
const MAP_FILE = path.join(ROOT, 'src', 'constants', 'characterChibiPickerImages.ts');

const CANVAS_W = 88;
const CANVAS_H = 104;
const MAX_CHAR_H = 78;
const PIXEL_CRUNCH_H = 42;

function repoFileName(characterName: string): string {
  return `${characterName}.png`;
}

async function bodyToPickerChibi(inputPath: string, outPath: string): Promise<void> {
  const trimmed = await sharp(inputPath).trim({ threshold: 12 }).png().toBuffer();

  const pixelized = await sharp(trimmed)
    .resize({ height: PIXEL_CRUNCH_H, kernel: sharp.kernel.nearest })
    .resize({ height: MAX_CHAR_H, kernel: sharp.kernel.nearest })
    .png()
    .toBuffer();

  const meta = await sharp(pixelized).metadata();
  const cw = meta.width ?? 1;
  const ch = meta.height ?? 1;
  const left = Math.max(0, Math.floor((CANVAS_W - cw) / 2));
  const charTop = Math.max(4, Math.floor((CANVAS_H - ch) / 2));

  await sharp({
    create: {
      width: CANVAS_W,
      height: CANVAS_H,
      channels: 4,
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    },
  })
    .composite([{ input: pixelized, top: charTop, left }])
    .png()
    .toFile(outPath);
}

function resolveSourcePath(id: string, name: string, index: number): string {
  const generated = path.join(GEN_SRC, `${id}.png`);
  if (fs.existsSync(generated)) return generated;
  const named = path.join(BODY_NAMED, repoFileName(name));
  if (fs.existsSync(named)) return named;
  return path.join(BODY_NUM, `${index + 1}.png`);
}

function writePickerMap(): void {
  const header = `/**
 * AUTO-GENERATED by npm run build:picker-chibi
 * 选人 / 图鉴卡片立绘（SD 像素小人，透明底，由全身立绘离线生成）。
 */
import type { ImageSourcePropType } from 'react-native';

`;

  const lines = CHARACTERS.map(
    (c) => `  '${c.id}': require('../../assets/characters/chibi/${c.id}.png'),`
  );

  const body = `${header}export const CHIBI_PICKER_BY_ID: Record<string, ImageSourcePropType> = {
${lines.join('\n')}
};

export function getChibiPickerPortraitById(characterId: string): ImageSourcePropType | undefined {
  return CHIBI_PICKER_BY_ID[characterId];
}
`;

  fs.writeFileSync(MAP_FILE, body, 'utf8');
}

async function main(): Promise<void> {
  fs.mkdirSync(OUT_NAMED, { recursive: true });
  fs.mkdirSync(OUT_NUM, { recursive: true });

  for (let i = 0; i < CHARACTERS.length; i++) {
    const c = CHARACTERS[i]!;
    const src = resolveSourcePath(c.id, c.name, i);
    if (!fs.existsSync(src)) {
      console.warn('skip missing body:', c.id, c.name, src);
      continue;
    }
    const outNamed = path.join(OUT_NAMED, repoFileName(c.name));
    const outId = path.join(OUT_NUM, `${c.id}.png`);
    await bodyToPickerChibi(src, outNamed);
    await fs.promises.copyFile(outNamed, outId);
    console.log('chibi', c.id, c.name);
  }

  writePickerMap();
  console.log('Wrote', MAP_FILE);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
