/**
 * Batch-generate AI character bust portraits from `CHARACTERS` in `src/data/mockData.ts`
 * using the OpenAI Images API (default model: gpt-image-2).
 *
 * Prerequisites:
 *   export OPENAI_API_KEY="sk-..."
 *
 * Usage:
 *   npm run gen:avatars
 *   npm run gen:avatars -- --dry-run
 *   npm run gen:avatars -- --only=1,3,5
 *   npm run gen:avatars -- --skip-existing --delay-ms=2000
 *
 * Optional env:
 *   OPENAI_IMAGE_MODEL   (default: gpt-image-2)
 *   OPENAI_IMAGE_SIZE    (default: 1024x1024)
 *   OPENAI_IMAGE_QUALITY (default: medium; low|medium|high|auto)
 */

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

import type { AICharacter } from '../src/types';
import { CHARACTERS } from '../src/data/mockData';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'assets', 'avatars', 'generated');
const MAP_FILE = path.join(ROOT, 'src', 'constants', 'characterAvatarGeneratedMap.ts');

const SERIES_STYLE = [
  'Game UI portrait asset, same art direction for every image in this series.',
  'Chibi / super-deformed bust (head and upper shoulders only), centered.',
  'Very thick clean black outlines on all shapes, flat cel shading with soft hand-painted watercolor / gouache color washes on top (visible brush texture, slightly imperfect edges, cheerful pastel palette).',
  'Plain flat white background, no frame, no text, no watermark, no UI chrome.',
  'Not photorealistic; not 3D render; not glossy anime airbrush.',
].join(' ');

function parseArgs(argv: string[]) {
  const dryRun = argv.includes('--dry-run');
  let only: Set<string> | null = null;
  let delayMs = 1200;
  let skipExisting = false;
  for (const a of argv) {
    if (a.startsWith('--only=')) {
      only = new Set(
        a
          .slice('--only='.length)
          .split(',')
          .map((s) => s.trim())
          .filter(Boolean),
      );
    }
    if (a.startsWith('--delay-ms=')) {
      delayMs = Math.max(0, Number(a.slice('--delay-ms='.length)) || 0);
    }
    if (a === '--skip-existing') skipExisting = true;
  }
  return { dryRun, only, delayMs, skipExisting };
}

function sleep(ms: number) {
  return new Promise((r) => setTimeout(r, ms));
}

function buildPrompt(c: AICharacter): string {
  const bits = [
    SERIES_STYLE,
    `Character name: ${c.name}.`,
    `Age: ${c.age}. Present age-appropriate face and styling (elderly looks elderly, teens look young).`,
    `Gender presentation: ${c.gender}.`,
    `Constellation vibe (subtle, optional accessory or palette hint only): ${c.constellation}.`,
    `Personality to read in expression and pose: ${c.personality}.`,
    `Difficulty tier (tone of expression): ${c.difficulty}.`,
    `One-line bio for mood only: ${c.description}`,
  ];
  return bits.join(' ');
}

async function generateOne(
  apiKey: string,
  model: string,
  size: string,
  quality: string,
  prompt: string,
): Promise<Buffer> {
  const res = await fetch('https://api.openai.com/v1/images/generations', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${apiKey}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      model,
      prompt,
      n: 1,
      size,
      quality,
      moderation: 'low',
      background: 'opaque',
      output_format: 'png',
    }),
  });

  const raw = await res.text();
  if (!res.ok) {
    throw new Error(`OpenAI images error ${res.status}: ${raw.slice(0, 2000)}`);
  }
  let json: { data?: Array<{ b64_json?: string }> };
  try {
    json = JSON.parse(raw) as { data?: Array<{ b64_json?: string }> };
  } catch {
    throw new Error(`Invalid JSON from OpenAI: ${raw.slice(0, 500)}`);
  }
  const b64 = json.data?.[0]?.b64_json;
  if (!b64) {
    throw new Error(`No b64_json in response: ${raw.slice(0, 800)}`);
  }
  return Buffer.from(b64, 'base64');
}

function writeMapFile() {
  if (!fs.existsSync(OUT_DIR)) fs.mkdirSync(OUT_DIR, { recursive: true });
  const files = fs.readdirSync(OUT_DIR).filter((f) => /^\d+\.png$/.test(f));
  const ids = files
    .map((f) => f.replace('.png', ''))
    .sort((a, b) => Number(a) - Number(b));

  const header = `/**
 * AUTO-GENERATED by npm run gen:avatars. Maps AI character id to assets/avatars/generated/.
 * Re-run after changing characters in mockData.
 */
import type { ImageSourcePropType } from 'react-native';

`;

  const body =
    ids.length === 0
      ? `export const GENERATED_AI_AVATARS: Partial<Record<string, ImageSourcePropType>> = {};
`
      : `export const GENERATED_AI_AVATARS: Partial<Record<string, ImageSourcePropType>> = {
${ids.map((id) => `  '${id}': require('../../assets/avatars/generated/${id}.png'),`).join('\n')}
};
`;

  fs.writeFileSync(MAP_FILE, header + body, 'utf8');
}

async function main() {
  const { dryRun, only, delayMs, skipExisting } = parseArgs(process.argv.slice(2));
  const apiKey = process.env.OPENAI_API_KEY;
  const model = process.env.OPENAI_IMAGE_MODEL ?? 'gpt-image-2';
  const size = process.env.OPENAI_IMAGE_SIZE ?? '1024x1024';
  const quality = process.env.OPENAI_IMAGE_QUALITY ?? 'medium';

  if (!fs.existsSync(OUT_DIR)) fs.mkdirSync(OUT_DIR, { recursive: true });

  let list = [...CHARACTERS];
  if (only) list = list.filter((c) => only.has(c.id));

  if (!apiKey && !dryRun) {
    console.error('Missing OPENAI_API_KEY. Set it or pass --dry-run to print prompts only.');
    process.exit(1);
  }

  console.log(`Model=${model} size=${size} quality=${quality} characters=${list.length} dryRun=${dryRun}`);

  for (const c of list) {
    const outPath = path.join(OUT_DIR, `${c.id}.png`);
    if (skipExisting && fs.existsSync(outPath)) {
      console.log(`skip existing ${c.id} ${c.name}`);
      continue;
    }
    const prompt = buildPrompt(c);
    if (dryRun) {
      console.log(`\n--- ${c.id} ${c.name} ---\n${prompt}\n`);
      continue;
    }
    console.log(`generating ${c.id} ${c.name}...`);
    const buf = await generateOne(apiKey!, model, size, quality, prompt);
    fs.writeFileSync(outPath, buf);
    if (delayMs > 0) await sleep(delayMs);
  }

  if (!dryRun) {
    writeMapFile();
    console.log(`Wrote ${MAP_FILE}`);
  } else {
    console.log('Dry run: left characterAvatarGeneratedMap.ts unchanged.');
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
