/**
 * 从全身立绘生成局内头像 → assets/avatars/generated/{id}.png（白底、统一尺寸）
 *
 *   npm run build:bust-avatars
 *   npm run build:bust-avatars -- --only=8
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

import sharp from 'sharp';

import { CHARACTERS } from '../src/data/mockData';
import { parseCharacterArtArgs, repoBodyFileName } from './lib/characterArtShared';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const NAMED_DIR = path.join(ROOT, 'assets', 'characters', 'body', 'named');
const BODY_NUM_DIR = path.join(ROOT, 'assets', 'characters', 'body');
const GEN_SRC = path.join(ROOT, 'assets', 'characters', 'body', 'generated-src');
const OUT_DIR = path.join(ROOT, 'assets', 'avatars', 'generated');
const MAP_FILE = path.join(ROOT, 'src', 'constants', 'characterAvatarGeneratedMap.ts');

const OUT_SIZE = 256;

/** 全身立绘内容框（相对上一版 +50%） */
const BUST_SLOT_H = Math.round(246 * 1.5);
const BUST_SLOT_W = Math.round(218 * 1.5);
/** 距画布顶部的下移（px）；不裁头顶，超出则只裁脚底 */
const BUST_SHIFT_DOWN = 30;

/** Sam 立绘在资源里偏小，略放大 */
const SAM_CHARACTER_ID = '8';
const SAM_SLOT_SCALE = 1.04;

/** Tom 再比其他人多 +10% */
const TOM_CHARACTER_ID = '10';
const TOM_SLOT_SCALE = 1.1;

function resolveBodyPath(c: (typeof CHARACTERS)[0], index: number): string | null {
  const named = path.join(NAMED_DIR, repoBodyFileName(c.name));
  if (fs.existsSync(named)) return named;
  const gen = path.join(GEN_SRC, `${c.id}.png`);
  if (fs.existsSync(gen)) return gen;
  const num = path.join(BODY_NUM_DIR, `${index + 1}.png`);
  if (fs.existsSync(num)) return num;
  return null;
}

function slotScaleFor(characterId: string): number {
  let scale = 1;
  if (characterId === SAM_CHARACTER_ID) scale *= SAM_SLOT_SCALE;
  if (characterId === TOM_CHARACTER_ID) scale *= TOM_SLOT_SCALE;
  return scale;
}

function slotSizeFor(characterId: string): { w: number; h: number } {
  const scale = slotScaleFor(characterId);
  return {
    w: Math.round(BUST_SLOT_W * scale),
    h: Math.round(BUST_SLOT_H * scale),
  };
}

/** 贴入 256 画布：从顶部下移，不裁头顶；过高则只裁脚底，过宽则裁两侧 */
async function fitBustToCanvas(
  bust: Buffer,
  bw: number,
  bh: number
): Promise<{ bust: Buffer; bw: number; bh: number; top: number; left: number }> {
  const top = BUST_SHIFT_DOWN;
  const maxVisibleH = Math.max(1, OUT_SIZE - top);
  const visibleH = Math.max(1, Math.min(bh, maxVisibleH));
  const cropLeft = bw > OUT_SIZE ? Math.floor((bw - OUT_SIZE) / 2) : 0;
  const visibleW = Math.max(1, Math.min(OUT_SIZE, bw - cropLeft));
  let outBust = bust;
  if (cropLeft > 0 || visibleH < bh || visibleW < bw) {
    outBust = await sharp(bust)
      .extract({ left: cropLeft, top: 0, width: visibleW, height: visibleH })
      .png()
      .toBuffer();
    bw = visibleW;
    bh = visibleH;
  }
  return {
    bust: outBust,
    bw,
    bh,
    top,
    left: Math.max(0, Math.floor((OUT_SIZE - bw) / 2)),
  };
}

async function bodyToBustAvatar(
  inputPath: string,
  outPath: string,
  characterId: string
): Promise<void> {
  const trimmedBuf = await sharp(inputPath).trim({ threshold: 12 }).png().toBuffer();
  const { w: slotW, h: slotH } = slotSizeFor(characterId);

  let bust = await sharp(trimmedBuf)
    .resize(slotW, slotH, {
      fit: 'inside',
      kernel: sharp.kernel.nearest,
    })
    .png()
    .toBuffer();

  const bustMeta = await sharp(bust).metadata();
  let bw = bustMeta.width ?? 1;
  let bh = bustMeta.height ?? 1;
  const fitted = await fitBustToCanvas(bust, bw, bh);
  bust = fitted.bust;
  bw = fitted.bw;
  bh = fitted.bh;
  const { top, left } = fitted;

  await sharp({
    create: {
      width: OUT_SIZE,
      height: OUT_SIZE,
      channels: 4,
      background: { r: 255, g: 255, b: 255, alpha: 1 },
    },
  })
    .composite([{ input: bust, top, left }])
    .png()
    .toFile(outPath);
}

function writeMapFile(ids: string[]) {
  const header = `/**
 * AUTO-GENERATED by npm run build:bust-avatars
 * 局内头像（白底、全身缩放）：由 assets/characters/body 立绘生成。
 */
import type { ImageSourcePropType } from 'react-native';

`;

  const body =
    ids.length === 0
      ? `export const GENERATED_AI_AVATARS: Partial<Record<string, ImageSourcePropType>> = {};
`
      : `export const GENERATED_AI_AVATARS: Partial<Record<string, ImageSourcePropType>> = {
${ids.map((id) => `  '${id}': require('../../assets/avatars/generated/${id}.png'),`).join('\n')}
};
`;

  fs.writeFileSync(MAP_FILE, header + body, 'utf8');
}

async function main() {
  const { only } = parseCharacterArtArgs(process.argv.slice(2));
  fs.mkdirSync(OUT_DIR, { recursive: true });

  let list = [...CHARACTERS];
  if (only) list = list.filter((c) => only.has(c.id));

  const written: string[] = [];

  for (let i = 0; i < list.length; i++) {
    const c = list[i]!;
    const index = CHARACTERS.findIndex((x) => x.id === c.id);
    const src = resolveBodyPath(c, index >= 0 ? index : i);
    if (!src) {
      console.warn(`skip ${c.id} ${c.name}: no body source`);
      continue;
    }
    const outPath = path.join(OUT_DIR, `${c.id}.png`);
    await bodyToBustAvatar(src, outPath, c.id);
    written.push(c.id);
    const slot = slotSizeFor(c.id);
    console.log(`bust ${c.id} ${c.name} <- ${path.basename(src)} (${slot.w}x${slot.h})`);
  }

  writeMapFile(
    written
      .map((id) => id)
      .sort((a, b) => Number(a) - Number(b))
  );
  console.log(`Wrote ${written.length} avatars -> ${MAP_FILE}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
